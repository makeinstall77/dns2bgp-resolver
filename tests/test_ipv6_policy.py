@pytest.mark.asyncio
async def test_rebuild_triggers_suppress(repo, tmp_path: Path):
    path = tmp_path / "list.domains"
    settings = Ipv6Settings(
        mode="suppress",
        dnsdist_list_path=str(path),
        dnsdist_reload_enable=False,
    )
    policy = ModeBasedIpv6Policy(settings)
    idx = DomainIndex()
    svc = DomainIndexService(repo, idx, ipv6_policy=policy)
    await repo.add(Domain.create("manual.test", source="manual"))
    size = await svc.rebuild()
    assert size == 1
    assert "manual.test" in path.read_text(encoding="utf-8")


