def test_names_snapshot():
    idx = DomainIndex()
    idx.rebuild(rules=[("exact.com", "exact"), ("suffix.com", "suffix")])
    assert idx.names_snapshot() == frozenset({"exact.com", "suffix.com"})


@pytest.mark.asyncio
async def test_dnsdist_exporter_writes_sorted(tmp_path: Path):
    path = tmp_path / "aaaa-suppress.domains"
    settings = Ipv6Settings(
        mode="suppress",
        dnsdist_list_path=str(path),
        dnsdist_reload_enable=False,
    )
    exporter = DnsdistDomainListExporter(settings)
    await exporter.export({"zeta.test", "alpha.test"})
    text = path.read_text(encoding="utf-8")
    assert "# generated by dns2bgp-resolver" in text
    lines = [ln for ln in text.splitlines() if ln and not ln.startswith("#")]
    assert lines == ["alpha.test", "zeta.test"]


